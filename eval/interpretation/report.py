"""
Interpretation per representation and per category, from a run's probe-prompt trials
(eval/interpretation/__init__.py): printed, and written to
runs/<dir>/analysis/interpretation.tex by `report_run`.

Injected rows are grouped by representation and by category; control rows (eval/trials.py)
are listed apart, and baseline rows give the false-positive rate of the keyword check.
Errored trials are left out.
"""

from __future__ import annotations

from pathlib import Path

from eval.interpretation import is_probe
from eval.interpretation.score import items, names_action, names_object
from eval.tables import _ci, _rate, _table, _tex
from eval.trials import LEVEL_ORDER, _order, group_by, split


def _counts(trials: list[dict]) -> tuple[int, int, int]:
    """(n, replies naming the object, replies naming object and action)."""
    return len(trials), sum(map(names_object, trials)), sum(map(names_action, trials))


def interpretation_rows(trials: list[dict], rep_order: list | None = None) -> dict:
    """Counts for the probe trials among `trials`: {"representation": [(rep, category, n,
    object, action)], "category": [(category, n, object, action)], "control": [...as
    representation], "baseline": (n, false positives)}."""
    injected, control, baseline, _ = split([t for t in trials if is_probe(t)])

    def by_rep(ts):
        groups = group_by(ts, "representation_id")
        return [(rep, groups[rep][0].get("category"), *_counts(groups[rep])) for rep in _order(groups, rep_order)]

    cats = group_by(injected, "category")
    every_item = sorted({i for t in injected + control for i in items(t)})
    return {
        "representation": by_rep(injected),
        "category": [(c, *_counts(cats[c])) for c in _order(cats, LEVEL_ORDER)],
        "control": by_rep(control),
        "baseline": (len(baseline), sum(names_object(t, every_item) for t in baseline)),
    }


def _pct(k: int, n: int) -> str:
    return f"{k}/{n} ({100 * k / n:.0f}%)" if n else "-"


def report_text(rows: dict) -> str:
    lines = ["  interpretation (probe prompts; reply names the injection's object | and its action)"]
    for key in ("representation", "control"):
        lines += [f"    {str(rep):<24}{str(cat):<13}{_pct(k, n):>14}   {_pct(a, n):>14}"
                  for rep, cat, n, k, a in rows[key]] + ([""] if rows[key] else [])
    for cat, n, k, a in rows["category"]:
        lines.append(f"    {str(cat):<37}{_pct(k, n):>14}   {_pct(a, n):>14}")
    n, fp = rows["baseline"]
    lines.append(f"  baseline {n:>5} trials   name an injected object (false positives) {_pct(fp, n)}")
    return "\n".join(lines)


def report_tex(rows: dict, model: str | None) -> str:
    m = _tex(model)
    head = "$N$ & Names object & 95\\% CI & Object and action"

    def row(*keys, n, k, a):
        return " & ".join(_tex(x) for x in keys) + f" & {n} & {_rate(k, n)} & {_ci(k, n)} & {_rate(a, n)} \\\\"

    reps = [row(rep, cat, n=n, k=k, a=a) for rep, cat, n, k, a in rows["representation"]]
    if rows["control"]:
        reps += ["\\midrule", *(row(rep, cat, n=n, k=k, a=a) for rep, cat, n, k, a in rows["control"])]
    n, fp = rows["baseline"]
    out = [f"% Generated by eval/interpretation for {m}. Needs \\usepackage{{booktabs}}.", ""]
    out += _table(f"Interpretation by representation ({m}): replies to the probe prompts that name the "
                  "injection's object (keyword check, eval/interpretation/score.py). Control rows last. "
                  f"Baseline replies naming an injected object: {_rate(fp, n)}.",
                  "tab:interpretation", "llrlll", "Representation & Category & " + head, reps)
    out += _table(f"Interpretation by category ({m}).", "tab:interpretation-category", "lrlll",
                  "Category & " + head, [row(cat, n=n, k=k, a=a) for cat, n, k, a in rows["category"]])
    return "\n".join(out)


def report_run(trials: list[dict], model: str | None, out_dir: Path, rep_order: list | None = None) -> Path | None:
    """Print the interpretation report and write interpretation.tex; None when the run has
    no probe trials."""
    if not any(is_probe(t) for t in trials):
        return None
    rows = interpretation_rows(trials, rep_order)
    print(report_text(rows))
    out = out_dir / "interpretation.tex"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(report_tex(rows, model), encoding="utf-8")
    return out
