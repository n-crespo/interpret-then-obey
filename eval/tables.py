"""tables.tex: booktabs tables of one run's trials, written by `analyze_run` in
eval/analyze.py. Attack success by representation and by factor, every outcome per
prompt, injected against controls and baseline, and decoy picks on the legend
representations. Control rows (eval/trials.py) are listed apart from injected rows and
left out of their totals.
"""

from __future__ import annotations

from eval.classify import LEGEND_PREFIX, OUTCOMES
from eval.trials import LEVEL_ORDER, _order, group_by, split, summarize, wilson

# Factor table: (manifest field, label)
FACTOR_ROWS = [("category", "Category"), ("script", "Script"), ("prompt_id", "Prompt"), ("context_id", "Context")]
ASR = "attack_success"
SHOWN = [o for o in OUTCOMES if o != "harness_error"]  # errored trials are left out of every rate


def picked_decoy(t: dict) -> bool:
    """Some call of the trial named a decoy (eval/classify.py)."""
    return any("decoy" in label for label in t["labels"])


def _tex(s) -> str:
    s = "--" if s is None else str(s)
    for a, b in [("\\", "\\textbackslash{}"), ("&", "\\&"), ("%", "\\%"), ("_", "\\_"), ("#", "\\#"),
                 ("$", "\\$"), ("{", "\\{"), ("}", "\\}")]:
        s = s.replace(a, b) if a != "\\" else s.replace(a, "\x00")
    return s.replace("\x00", "\\textbackslash{}")


def _rate(k: int, n: int) -> str:
    return f"{k}/{n} ({100 * k / n:.0f}\\%)" if n else "--"


def _ci(k: int, n: int) -> str:
    lo, hi = wilson(k, n)
    return f"{100 * lo:.0f}--{100 * hi:.0f}" if n else "--"


def _asr(trials: list[dict]) -> str:
    s = summarize(trials)
    return f"{s['n']} & {_rate(s[ASR], s['n'])} & {_ci(s[ASR], s['n'])}"


def _table(caption: str, label: str, cols: str, head: str, rows: list[str]) -> list[str]:
    return ["\\begin{table}[ht]", "\\centering", "\\small", f"\\caption{{{caption}}}", f"\\label{{{label}}}",
            f"\\begin{{tabular}}{{{cols}}}", "\\toprule", head + " \\\\", "\\midrule", *rows,
            "\\bottomrule", "\\end{tabular}", "\\end{table}", ""]


def latex_tables(trials: list[dict], model: str | None, rep_order: list | None = None) -> str:
    """Three booktabs tables. Needs \\usepackage{booktabs} in the preamble. Attack success
    is counted on injected rows; errored trials are left out."""
    injected, control, baseline, _ = split(trials)
    m = _tex(model)
    out = [f"% Generated by eval/analyze.py for {m}. Needs \\usepackage{{booktabs}}.", ""]

    # 1. By representation; controls last, outside the injected total
    def by_rep(ts: list[dict]) -> list[str]:
        groups = group_by(ts, "representation_id")
        return [f"{_tex(rep)} & {_tex(groups[rep][0]['category'])} & {_tex(groups[rep][0]['script'])} & "
                f"{_asr(groups[rep])} \\\\" for rep in _order(groups, rep_order)]

    rows = by_rep(injected)
    if injected:
        rows += ["\\midrule", f"All injected & & & {_asr(injected)} \\\\"]
    if control:
        rows += ["\\midrule", *by_rep(control)]
    out += _table(f"Attack success by representation ({m}). CI: 95\\% Wilson interval. Baseline rows show no "
                  "injection and are never attack success; their outcomes are in Table~\\ref{tab:by-prompt}. "
                  "Control rows (last, not in All injected) show the injection's object with no command, so "
                  "their rate is priming by the object, not obeying.",
                  "tab:by-representation", "lllrll",
                  "Representation & Category & Script & $N$ & Attack success & 95\\% CI", rows)

    # 2. By factor (injected rows)
    rows = []
    for field, label in FACTOR_ROWS:
        groups = group_by(injected, field)
        groups.pop(None, None)
        if rows and groups:
            rows.append("\\midrule")
        rows += [f"{label if i == 0 else ''} & {_tex(key)} & {_asr(groups[key])} \\\\"
                 for i, key in enumerate(_order(groups, LEVEL_ORDER))]
    out += _table(f"Attack success on injected rows by factor ({m}). Script leaves out rows without one "
                  "(symbol representations).", "tab:by-factor", "llrll",
                  "Factor & Level & $N$ & Attack success & 95\\% CI", rows)

    # 3. Every outcome per prompt, injected against baseline
    rows = []
    for prompt in _order({t["prompt_id"] for t in injected + control + baseline}, LEVEL_ORDER):
        first = True
        for kind, ts in (("injected", injected), ("control", control), ("baseline", baseline)):
            s = summarize([t for t in ts if t["prompt_id"] == prompt])
            if s["n"]:
                rows.append(f"{_tex(prompt) if first else ''} & {kind} & {s['n']} & "
                            + " & ".join(_rate(s[o], s["n"]) for o in SHOWN) + " \\\\")
                first = False
    out += _table(f"Outcomes per prompt ({m}), injected rows against the controls and the no-injection "
                  "baseline. Each trial has "
                  "one outcome.", "tab:by-prompt", "llr" + "l" * len(SHOWN),
                  "Prompt & Rows & $N$ & " + " & ".join(o.replace("_", " ").capitalize() for o in SHOWN), rows)

    # 4. Decoy picks on the legend representations
    groups = {rep: ts for rep, ts in group_by(injected, "representation_id").items()
              if str(rep).startswith(LEGEND_PREFIX)}
    rows = []
    for rep in _order(groups, rep_order):
        k, n = sum(map(picked_decoy, groups[rep])), len(groups[rep])
        rows.append(f"{_tex(rep)} & {_asr(groups[rep])} & {_rate(k, n)} & {_ci(k, n)} \\\\")
    if rows:
        out += _table(f"Decoy picks on the legend representations ({m}): trials with a call naming a known target "
                      "object that is neither the scene's nor the injection's, such as another glyph of the legend.",
                      "tab:decoys", "lrllll",
                      "Representation & $N$ & Attack success & 95\\% CI & Decoy picks & 95\\% CI", rows)
    return "\n".join(out)
